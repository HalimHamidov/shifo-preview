    function collectI18nNodes() {
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
          const parentTag = node.parentElement?.tagName;
          const key = node.nodeValue.trim();
          if (!key || parentTag === "SCRIPT" || parentTag === "STYLE") {
            return NodeFilter.FILTER_REJECT;
          }
          return hasTranslation(key) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
        }
      });

      while (walker.nextNode()) {
        const node = walker.currentNode;
        const value = node.nodeValue;
        textNodes.push({
          node,
          key: value.trim(),
          prefix: value.match(/^\s*/)[0],
          suffix: value.match(/\s*$/)[0]
        });
      }

      document.querySelectorAll("[placeholder], [aria-label]").forEach((element) => {
        ["placeholder", "aria-label"].forEach((attr) => {
          const key = element.getAttribute(attr);
          if (key && hasTranslation(key)) {
            attrNodes.push({ element, attr, key });
          }
        });
      });
    }

