    function buildCarousel(slides, className, label, delay) {
      if (!slides.length) {
        return null;
      }

      const carousel = document.createElement("div");
      carousel.className = `media-carousel ${className}`;
      carousel.setAttribute("aria-label", label);

      const viewport = document.createElement("div");
      viewport.className = "media-carousel-viewport";
      viewport.tabIndex = 0;

      const track = document.createElement("div");
      track.className = "media-carousel-track";

      slides.forEach((slide) => {
        slide.classList.add("carousel-slide");
        track.appendChild(slide);
      });

      viewport.appendChild(track);
      carousel.appendChild(viewport);

      const makeButton = (direction, labelText, path) => {
        const button = document.createElement("button");
        button.type = "button";
        button.className = `carousel-nav ${direction}`;
        button.setAttribute("aria-label", labelText);
        button.innerHTML = `<svg viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="${path}"/></svg>`;
        carousel.appendChild(button);
        return button;
      };

      const prev = makeButton("prev", "Предыдущее", "M15.4 5 8.4 12l7 7-1.8 1.8L4.8 12l8.8-8.8L15.4 5Z");
      const next = makeButton("next", "Следующее", "m8.6 5 1.8-1.8 8.8 8.8-8.8 8.8L8.6 19l7-7-7-7Z");
      const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
      let timer = null;
      let resumeTimer = null;

      const getSlides = () => Array.from(track.children);
      const currentIndex = () => {
        const left = viewport.getBoundingClientRect().left;
        return getSlides().reduce((best, slide, index) => {
          const distance = Math.abs(slide.getBoundingClientRect().left - left);
          return distance < best.distance ? { index, distance } : best;
        }, { index: 0, distance: Infinity }).index;
      };

      const pauseVideos = () => {
        carousel.querySelectorAll("video").forEach((video) => video.pause());
      };

      const go = (direction) => {
        const items = getSlides();
        if (!items.length) {
          return;
        }

        pauseVideos();
        const nextIndex = (currentIndex() + direction + items.length) % items.length;
        const target = items[nextIndex];
        const viewportRect = viewport.getBoundingClientRect();
        const targetRect = target.getBoundingClientRect();
        const left = viewport.scrollLeft + targetRect.left - viewportRect.left;
        viewport.scrollTo({ left, behavior: "smooth" });
      };

      const stop = () => {
        window.clearInterval(timer);
        timer = null;
      };

      const start = () => {
        if (prefersReducedMotion || timer || !delay) {
          return;
        }
        timer = window.setInterval(() => {
          if (!document.hidden) {
            go(1);
          }
        }, delay);
      };

      const resumeLater = () => {
        stop();
        window.clearTimeout(resumeTimer);
        resumeTimer = window.setTimeout(start, delay * 2);
      };

      prev.addEventListener("click", () => {
        go(-1);
        resumeLater();
      });

      next.addEventListener("click", () => {
        go(1);
        resumeLater();
      });

      viewport.addEventListener("pointerdown", resumeLater, { passive: true });
      viewport.addEventListener("wheel", resumeLater, { passive: true });
      viewport.addEventListener("keydown", (event) => {
        if (event.key === "ArrowLeft") {
          event.preventDefault();
          go(-1);
          resumeLater();
        }
        if (event.key === "ArrowRight") {
          event.preventDefault();
          go(1);
          resumeLater();
        }
      });

      carousel.querySelectorAll("video").forEach((video) => {
        video.addEventListener("play", stop);
        video.addEventListener("pause", resumeLater);
        video.addEventListener("ended", resumeLater);
      });

      document.addEventListener("visibilitychange", () => {
        if (document.hidden) {
          stop();
        } else {
          start();
        }
      });

      start();
      return carousel;
    }

